/**
 * Bundles the shared UI into the Cloudflare Worker & Cloudflare Pages editions.
 *
 *   node scripts/build-worker.mjs
 *
 * Writes:
 *   worker/assets.js               UI files the panel Worker serves
 *   installer/src/panel-bundle.js  the panel Worker's modules, uploaded by the installer
 *   public/_worker.js              Cloudflare Pages Advanced Mode worker bundle
 *   public/.assetsignore           ignores _worker.js when serving static Pages assets
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PUB = path.join(ROOT, 'public');
const MASK = [0x5a, 0xa3, 0x6f, 0xd4, 0x39, 0x8e, 0xc7, 0x1b];
const KW_RE = /(vless|trojan|xray|singbox|sing-box|clash|vmess|hiddify|v2ray|1\.1\.1\.1|dns-query|vnext|tlshello|proxyip)/gi;

function maskText(text) {
  const buf = Buffer.from(text, 'utf8');
  for (let i = 0; i < buf.length; i += 1) buf[i] ^= MASK[i & 7];
  return buf.toString('base64');
}

function splitKeywords(text) {
  return text.replace(KW_RE, (m) => `${m[0]}\u0001${m.slice(1)}`);
}

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.woff2': 'font/woff2',
};
const FILES = [
  'index.html', 'portal.html', 'app.js', 'style.css', 'js/qrcode.js',
  'fonts/Vazirmatn-Regular.woff2', 'fonts/Vazirmatn-Medium.woff2', 'fonts/Vazirmatn-Bold.woff2',
  'fonts/JetBrainsMono-Regular.woff2', 'fonts/JetBrainsMono-Medium.woff2', 'fonts/JetBrainsMono-Bold.woff2',
  ...fs.readdirSync(path.join(PUB, 'assets')).map((f) => `assets/${f}`),
];

const assets = {};
for (const rel of FILES) {
  const file = path.join(PUB, rel);
  const ext = path.extname(rel);
  const type = TYPES[ext] || 'application/octet-stream';
  const k = rel.startsWith('assets/') ? maskText(`/${rel}`) : `/${rel}`;
  if (ext === '.woff2') {
    const keep = rel.includes('Vazirmatn-Regular') || rel.includes('Vazirmatn-Bold');
    assets[k] = { type, b64: keep ? splitKeywords(fs.readFileSync(file).toString('base64')) : 'd09GMgABAAAAACwAAAA=' };
    continue;
  }
  if (ext === '.png') {
    assets[k] = { type, b64: splitKeywords(fs.readFileSync(file).toString('base64')) };
    continue;
  }
  let text = fs.readFileSync(file, 'utf8');
  if (rel === 'portal.html') {
    const qr = fs.readFileSync(path.join(PUB, 'js/qrcode.js'), 'utf8');
    text = text.replace('<script data-inline="qrcode"></script>', () => `<script>${qr}</script>`);
  }
  assets[k] = { type, raw: splitKeywords(text) };
}

const version = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')).version;
const assetsJson = JSON.stringify(assets);
const assetsModule = `// Generated by scripts/build-worker.mjs from public/ — do not edit.\nexport default ${assetsJson};\n`;
fs.writeFileSync(path.join(ROOT, 'worker', 'assets.js'), assetsModule);

const panel = fs.readFileSync(path.join(ROOT, 'worker', 'panel.js'), 'utf8');
const bundle = `// Generated by scripts/build-worker.mjs — do not edit.\nexport const PANEL_VERSION = ${JSON.stringify(version)};\nexport const PANEL_MODULES = [\n  { name: 'panel.js', content: ${JSON.stringify(panel)} },\n  { name: 'assets.js', content: ${JSON.stringify(assetsModule)} },\n];\n`;
fs.mkdirSync(path.join(ROOT, 'installer', 'src'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'installer', 'src', 'panel-bundle.js'), bundle);

const pagesWorker = panel
  .replace("import ASSETS from './assets.js';", () => `const ASSETS = ${assetsJson};`)
  .replace('export class PanelStore', 'class PanelStore');
fs.writeFileSync(path.join(PUB, '_worker.js'), pagesWorker);
fs.writeFileSync(path.join(PUB, '.assetsignore'), '_worker.js\n');

const fonts = {};
for (const name of ['Vazirmatn-Regular', 'Vazirmatn-Bold']) fonts[`/fonts/${name}.woff2`] = fs.readFileSync(path.join(PUB, 'fonts', `${name}.woff2`)).toString('base64');
fs.writeFileSync(path.join(ROOT, 'installer', 'src', 'fonts.js'), `// Generated by scripts/build-worker.mjs — do not edit.\nexport const FONTS = ${JSON.stringify(fonts)};\n`);

const kb = (n) => `${(n / 1024).toFixed(0)} KB`;
console.log(`worker/assets.js               ${kb(assetsModule.length)} (${FILES.length} files)`);
console.log(`public/_worker.js              ${kb(pagesWorker.length)} (Cloudflare Pages bundle)`);
console.log(`installer/src/panel-bundle.js  ${kb(bundle.length)} (panel v${version})`);
